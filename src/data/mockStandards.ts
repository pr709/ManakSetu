export function getStandardById(id: string): Standard | undefined {
  return mockStandards.find((s) => s.id === id || s.isNumber === id);
}

export function getRelatedStandards(standard: Standard): Standard[] {
  return standard.relatedStandards
    .map((isNum) => mockStandards.find((s) => s.isNumber === isNum))
    .filter((s): s is Standard => s !== undefined);
}
